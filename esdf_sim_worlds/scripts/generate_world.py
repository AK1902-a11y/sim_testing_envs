#!/usr/bin/env python3
"""Generate Gazebo Fortress worlds (SDF) plus the matching occupancy-grid maps for the ESDF benchmark.

  generate_world.py --all  [--worlds-dir D] [--maps-dir D] [--registry FILE]    # the testing_env* set
  generate_world.py OUT.sdf --preset simple_room [--size 10]                     # legacy single world

Every world is named "default" and carries the world-level systems the robot needs
(physics, user-commands, scene-broadcaster, sensors, imu). All worlds are STATIC.
The robot always spawns at world (0, 0, yaw 0), which is also AMCL's initial pose (config/amcl.yaml).
Maps are rasterised from the same geometry (0.05 m cells, exact footprints), so SDF and map always agree.
The registry (testing_envs.yaml) lists every env for the GUI: start pose, goal route, obstacle statistics.

testing_env1  simple_room   10x10 m, 4 obstacles                       sparse reference
testing_env2  dense_clutter 14x14 m, ~54 obstacles, gaps >= 0.8 m       many obstacles, still navigable
testing_env3  switchback    15 x 9.4 m, 3 lanes of 3 m, two U-turns    long parallel walls + head-on 90 degree turns
"""
import argparse
import collections
import math
import random
from os.path import join

OBST_H, WALL_H, WALL_T = 0.8, 1.0, 0.2
RES = 0.05            # map resolution [m]
ROBOT_R = 0.22
WALL_RGBA, OBST_RGBA = '0.5 0.5 0.55 1', '0.8 0.4 0.2 1'

HEADER = """<?xml version="1.0"?>
<!-- Generated by generate_world.py - edit the preset there, not this file. -->
<sdf version="1.8">
  <world name="default">
    <physics name="1ms" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="ignition-gazebo-physics-system" name="ignition::gazebo::systems::Physics"/>
    <plugin filename="ignition-gazebo-user-commands-system" name="ignition::gazebo::systems::UserCommands"/>
    <plugin filename="ignition-gazebo-scene-broadcaster-system" name="ignition::gazebo::systems::SceneBroadcaster"/>
    <plugin filename="ignition-gazebo-sensors-system" name="ignition::gazebo::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="ignition-gazebo-imu-system" name="ignition::gazebo::systems::Imu"/>
    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.8 0.8 0.8 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.5 0.1 -0.9</direction>
    </light>
    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision"><geometry><plane><normal>0 0 1</normal><size>100 100</size></plane></geometry></collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>100 100</size></plane></geometry>
          <material><ambient>0.8 0.8 0.8 1</ambient><diffuse>0.8 0.8 0.8 1</diffuse></material>
        </visual>
      </link>
    </model>
"""


# --------------------------------------------------------------------------- geometry specs
# A spec is a dict: room=(x0, x1, y0, y1) inner free rectangle, shapes=[(kind, name, x, y, dims, rgba)],
# goals=[(x, y)], title, description.  kind: 'box' dims=(sx, sy)  |  'cyl' dims=(r,)
def spec_simple_room():
    s = 5.0
    shapes = [
        ('box', 'box_1', 2.0, 1.5, (1.0, 0.6), OBST_RGBA),
        ('cyl', 'cyl_1', -2.0, 2.0, (0.4,), OBST_RGBA),
        ('box', 'box_2', -1.5, -2.5, (0.5, 0.5), OBST_RGBA),
        ('cyl', 'cyl_2', 2.5, -2.0, (0.25,), OBST_RGBA),
    ]
    return dict(
        room=(-s, s, -s, s), shapes=shapes,
        goals=[(3.5, 3.5), (-3.5, 3.5), (-3.5, -3.5), (3.5, -3.5), (0.0, 0.0)],
        title='Simple room (reference)',
        description='10x10 m room, 4 obstacles. Sparse: the easy reference case.')


def _bound_r(kind, dims):
    return math.hypot(dims[0], dims[1]) / 2 if kind == 'box' else dims[0]


def spec_dense_clutter(seed=7, half=7.0, gap=0.8, wall_gap=0.8, start_clear=1.4, target=90):
    """Poisson-style rejection sampling. gap = min free distance between any two obstacles (conservative:
    measured between bounding circles), so the real gaps are >= gap. The robot is 0.44 m wide."""
    rnd = random.Random(seed)
    placed = []   # (kind, x, y, dims, bound_r)
    for _ in range(200000):
        if len(placed) >= target:
            break
        if rnd.random() < 0.55:
            kind, dims = 'box', (round(rnd.uniform(0.4, 1.0), 2), round(rnd.uniform(0.4, 1.0), 2))
        else:
            kind, dims = 'cyl', (round(rnd.uniform(0.2, 0.5), 2),)
        br = _bound_r(kind, dims)
        lim = half - br - wall_gap
        x, y = rnd.uniform(-lim, lim), rnd.uniform(-lim, lim)
        if math.hypot(x, y) < br + start_clear:
            continue
        if any(math.hypot(x - p[1], y - p[2]) < br + p[4] + gap for p in placed):
            continue
        placed.append((kind, round(x, 2), round(y, 2), dims, br))
    shapes = [(k, f'obs_{i + 1}', x, y, d, OBST_RGBA) for i, (k, x, y, d, _) in enumerate(placed)]
    return dict(
        room=(-half, half, -half, half), shapes=shapes, goals=None,   # goals chosen after rasterising
        title='Dense clutter',
        description=f'{2 * half:.0f}x{2 * half:.0f} m room, {len(shapes)} boxes/cylinders, gaps >= {gap} m '
                    f'(seed {seed}). Many obstacles, still navigable.')


def spec_switchback():
    # Lanes: y in [-1.5,1.5], [1.7,4.7], [4.9,7.9]; interior walls at y=1.6 and y=4.8 (0.2 thick), x in [-1.5,13.5].
    # Wall A joins the west wall (gap of 3 m at the east end), wall B joins the east wall (gap at the west end).
    x0, x1 = -1.5, 13.5
    shapes = [
        ('box', 'lane_wall_a', (x0 + 10.5) / 2, 1.6, (10.5 - x0, WALL_T), WALL_RGBA),
        ('box', 'lane_wall_b', (1.5 + x1) / 2, 4.8, (x1 - 1.5, WALL_T), WALL_RGBA),
    ]
    return dict(
        room=(x0, x1, -1.5, 7.9), shapes=shapes,
        goals=[(12.0, 0.0), (12.0, 3.2), (0.0, 3.2), (0.0, 6.4), (12.0, 6.4)],
        title='Switchback hall',
        description='15 x 9.4 m, three 3 m lanes joined by two U-turns. Straight lanes with parallel walls '
                    '(best case) and lane-end turns with a head-on wall plus a long wall leaving the view (worst).')


ENVS = {
    'testing_env1': spec_simple_room,
    'testing_env2': spec_dense_clutter,
    'testing_env3': spec_switchback,
}


# --------------------------------------------------------------------------- SDF
def static_model(name, x, y, z, geom, rgba):
    return f"""    <model name="{name}">
      <static>true</static>
      <pose>{x} {y} {z} 0 0 0</pose>
      <link name="link">
        <collision name="collision"><geometry>{geom}</geometry></collision>
        <visual name="visual"><geometry>{geom}</geometry>
          <material><ambient>{rgba}</ambient><diffuse>{rgba}</diffuse></material></visual>
      </link>
    </model>
"""


def box_g(sx, sy, sz):
    return f"<box><size>{sx} {sy} {sz}</size></box>"


def cyl_g(r, h):
    return f"<cylinder><radius>{r}</radius><length>{h}</length></cylinder>"


def outer_walls(room):
    x0, x1, y0, y1 = room
    w, h, t = x1 - x0, y1 - y0, WALL_T
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    return [  # (name, cx, cy, sx, sy): the inner face of each wall is on the room boundary
        ('wall_n', cx, y1 + t / 2, w + 2 * t, t),
        ('wall_s', cx, y0 - t / 2, w + 2 * t, t),
        ('wall_e', x1 + t / 2, cy, t, h),
        ('wall_w', x0 - t / 2, cy, t, h),
    ]


def make_sdf(spec):
    out = [HEADER]
    for name, x, y, sx, sy in outer_walls(spec['room']):
        out.append(static_model(name, round(x, 3), round(y, 3), WALL_H / 2, box_g(round(sx, 3), round(sy, 3), WALL_H), WALL_RGBA))
    for kind, name, x, y, dims, rgba in spec['shapes']:
        is_wall = rgba == WALL_RGBA
        h = WALL_H if is_wall else OBST_H
        geom = box_g(round(dims[0], 3), round(dims[1], 3), h) if kind == 'box' else cyl_g(dims[0], h)
        out.append(static_model(name, round(x, 3), round(y, 3), h / 2, geom, rgba))
    out.append("  </world>\n</sdf>\n")
    return ''.join(out)


# --------------------------------------------------------------------------- map
def rasterise(spec):
    import numpy as np
    x0, x1, y0, y1 = spec['room']
    gx0, gy0 = x0 - WALL_T - 2 * RES, y0 - WALL_T - 2 * RES          # small free margin around the walls
    nx = int(math.ceil((x1 - x0 + 2 * WALL_T + 4 * RES) / RES))
    ny = int(math.ceil((y1 - y0 + 2 * WALL_T + 4 * RES) / RES))
    xs = gx0 + (np.arange(nx) + 0.5) * RES
    ys = gy0 + (np.arange(ny) + 0.5) * RES
    X, Y = np.meshgrid(xs, ys)
    occ = np.zeros((ny, nx), bool)
    for _, cx, cy, sx, sy in outer_walls(spec['room']):
        occ |= (np.abs(X - cx) <= sx / 2) & (np.abs(Y - cy) <= sy / 2)
    for kind, _, cx, cy, dims, _ in spec['shapes']:
        if kind == 'box':
            occ |= (np.abs(X - cx) <= dims[0] / 2) & (np.abs(Y - cy) <= dims[1] / 2)
        else:
            occ |= (X - cx) ** 2 + (Y - cy) ** 2 <= dims[0] ** 2
    return occ, (gx0, gy0)


def inflate(occ, cells):
    import numpy as np
    out = occ.copy()
    ny, nx = occ.shape
    r = int(math.ceil(cells))
    for dy in range(-r, r + 1):
        for dx in range(-r, r + 1):
            if dx * dx + dy * dy > cells * cells or (dx == 0 and dy == 0):
                continue
            ys, yd = slice(max(0, dy), ny + min(0, dy)), slice(max(0, -dy), ny + min(0, -dy))
            xs, xd = slice(max(0, dx), nx + min(0, dx)), slice(max(0, -dx), nx + min(0, -dx))
            out[yd, xd] |= occ[ys, xs]
    return out


def reachable(blocked, start_cell):
    ny, nx = blocked.shape
    seen = [[False] * nx for _ in range(ny)]
    sy, sx = start_cell
    dq = collections.deque([(sy, sx)]); seen[sy][sx] = True
    while dq:
        y, x = dq.popleft()
        for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            yy, xx = y + dy, x + dx
            if 0 <= yy < ny and 0 <= xx < nx and not seen[yy][xx] and not blocked[yy, xx]:
                seen[yy][xx] = True; dq.append((yy, xx))
    return seen


def write_map(spec, occ, origin, maps_dir, name):
    import numpy as np
    from PIL import Image
    img = np.where(occ, 0, 254).astype(np.uint8)[::-1]            # row 0 = top (max y)
    Image.fromarray(img).save(join(maps_dir, f'{name}.pgm'))
    with open(join(maps_dir, f'{name}.yaml'), 'w') as f:
        f.write(f'image: {name}.pgm\nmode: trinary\nresolution: {RES}\n'
                f'origin: [{origin[0]:.3f}, {origin[1]:.3f}, 0]\nnegate: 0\n'
                'occupied_thresh: 0.65\nfree_thresh: 0.25\n')


def analyse(spec, occ, origin):
    """Connectivity of the route on the robot-inflated grid + obstacle statistics."""
    import numpy as np
    infl = inflate(occ, (ROBOT_R + 0.03) / RES)
    to_cell = lambda x, y: (int((y - origin[1]) / RES), int((x - origin[0]) / RES))
    seen = reachable(infl, to_cell(0.0, 0.0))
    ok = all(seen[to_cell(*g)[0]][to_cell(*g)[1]] for g in spec['goals'])
    free = ~infl
    reach_frac = float(np.mean([seen[y][x] for y, x in zip(*np.nonzero(free))])) if free.any() else 0.0
    # obstacle cells (excluding the outer walls) inside a 10x10 m window centred at random reachable points
    x0, x1, y0, y1 = spec['room']
    inner = occ.copy()
    for _, cx, cy, sx, sy in outer_walls(spec['room']):
        ys, xs = np.mgrid[0:occ.shape[0], 0:occ.shape[1]]
        X, Y = origin[0] + (xs + 0.5) * RES, origin[1] + (ys + 0.5) * RES
        inner &= ~((np.abs(X - cx) <= sx / 2 + 1e-9) & (np.abs(Y - cy) <= sy / 2 + 1e-9))
    edge = inner & inflate(~inner, 1.0)      # footprint cells that touch free space = what a lidar can mark
    w = int(10 / RES)
    counts, ecounts = [], []
    for cy in np.linspace(y0 + 1, y1 - 1, 7):
        for cx in np.linspace(x0 + 1, x1 - 1, 7):
            iy, ix = to_cell(cx, cy)
            win = inner[max(0, iy - w // 2):iy + w // 2, max(0, ix - w // 2):ix + w // 2]
            counts.append(int(win.sum()))
            ecounts.append(int(edge[max(0, iy - w // 2):iy + w // 2, max(0, ix - w // 2):ix + w // 2].sum()))
    return dict(goals_reachable=bool(ok), reachable_free_fraction=round(reach_frac, 3),
                occupied_fraction=round(float(inner.mean()), 4),
                footprint_cells_10m_window_mean=int(np.mean(counts)), edge_cells_10m_window_mean=int(np.mean(ecounts)),
                edge_cells_10m_window_max=int(np.max(ecounts)))


def pick_dense_goals(spec, occ, origin):
    """Four goals near the corners of the reachable area (>= 0.5 m from any obstacle), visited as a loop."""
    import numpy as np
    infl = inflate(occ, (ROBOT_R + 0.28) / RES)
    to_cell = lambda x, y: (int((y - origin[1]) / RES), int((x - origin[0]) / RES))
    seen = reachable(infl, to_cell(0.0, 0.0))
    x0, x1, y0, y1 = spec['room']
    goals = []
    for sx, sy in ((1, 1), (-1, 1), (-1, -1), (1, -1)):
        tx, ty = sx * (x1 - 1.6), sy * (y1 - 1.6)
        best = None
        for iy, ix in zip(*np.nonzero(~infl)):
            if not seen[iy][ix]:
                continue
            x, y = origin[0] + (ix + 0.5) * RES, origin[1] + (iy + 0.5) * RES
            d = math.hypot(x - tx, y - ty)
            if best is None or d < best[0]:
                best = (d, round(x, 2), round(y, 2))
        goals.append((best[1], best[2]))
    return goals


# --------------------------------------------------------------------------- driver
def build_all(worlds_dir, maps_dir, registry):
    import yaml
    reg = {}
    for name, fn in ENVS.items():
        spec = fn()
        occ, origin = rasterise(spec)
        if spec['goals'] is None:
            spec['goals'] = pick_dense_goals(spec, occ, origin)
        stats = analyse(spec, occ, origin)
        if not stats['goals_reachable']:
            raise SystemExit(f'{name}: a goal is not reachable for the robot - adjust the preset')
        open(join(worlds_dir, f'{name}.sdf'), 'w').write(make_sdf(spec))
        write_map(spec, occ, origin, maps_dir, name)
        reg[name] = dict(
            title=spec['title'], description=spec['description'], world=name, map=name,
            start=[0.0, 0.0, 0.0], room=[float(v) for v in spec['room']],
            goals=[[float(a), float(b)] for a, b in spec['goals']],
            obstacles=len(spec['shapes']), stats=stats)
        print(f"{name}: {spec['title']}: {len(spec['shapes'])} shapes, {stats}")
    with open(registry, 'w') as f:
        f.write('# Generated by generate_world.py - do not edit by hand.\n')
        yaml.safe_dump({'envs': reg}, f, sort_keys=False)
    print(f'wrote {registry}')


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('out', nargs='?', help='legacy: output .sdf for --preset')
    ap.add_argument('--preset', default='simple_room', choices=['simple_room'])
    ap.add_argument('--size', type=float, default=None)
    ap.add_argument('--all', action='store_true', help='generate the testing_env* worlds, maps and registry')
    ap.add_argument('--worlds-dir', default='.')
    ap.add_argument('--maps-dir', default='.')
    ap.add_argument('--registry', default='testing_envs.yaml')
    a = ap.parse_args()
    if a.all:
        build_all(a.worlds_dir, a.maps_dir, a.registry)
    else:
        spec = spec_simple_room()
        if a.size:
            s = a.size / 2.0
            spec['room'] = (-s, s, -s, s)
        open(a.out, 'w').write(make_sdf(spec))
        print(f'wrote {a.out} (simple_room)')
